_UC   = string.ascii_uppercase
_LC   = string.ascii_lowercase
_DIG  = string.digits
_B64  = string.ascii_letters + string.digits + "+/="
_B62  = string.ascii_letters + string.digits
_B62U = string.ascii_letters + string.digits + "_"
_B64U = string.ascii_letters + string.digits + "-_"
_HEX  = string.hexdigits[:16]


def _rand(chars: str, n: int) -> str:
    return "".join(RNG.choices(chars, k=n))


def _gen_aws_key_id() -> str:
    """AKIA + 16 uppercase-alphanumeric chars (structurally valid format)."""
    prefix = RNG.choice(["AKIA", "ASIA", "AROA"])
    return prefix + _rand(_UC + _DIG, 16)


def _gen_aws_secret() -> str:
    """40 base64 chars (structurally matches real format, never real)."""
    return _rand(_B64.replace("=", ""), 39) + "="


def _gen_github_pat(variant: str = "ghp") -> str:
    """GitHub PAT: variant_ + 36 alphanumeric chars."""
    return f"{variant}_" + _rand(_B62, 36)


def _gen_github_fg_pat() -> str:
    """Fine-grained PAT: github_pat_ + 82 alphanumeric-or-underscore chars."""
    return "github_pat_" + _rand(_B62U, 82)


def _gen_google_key() -> str:
    """AIza + 35 alphanumeric+underscore+dash chars."""
    return "AIza" + _rand(_B62 + "_-", 35)


def _gen_slack_bot() -> str:
    """xoxb-{10d}-{10d}-{24 alphanum}."""
    a = _rand(_DIG, 11)
    b = _rand(_DIG, 11)
    c = _rand(_B62, 24)
    return f"xoxb-{a}-{b}-{c}"


def _gen_slack_user() -> str:
    """xoxp-{11d}-{11d}-{11d}-{32 alphanum}."""
    a = _rand(_DIG, 11)
    b = _rand(_DIG, 11)
    c = _rand(_DIG, 11)
    d = _rand(_B62, 32)
    return f"xoxp-{a}-{b}-{c}-{d}"


def _gen_stripe_secret(mode: str = "live") -> str:
    """sk_{mode}_ + 40 alphanumeric chars."""
    return f"sk_{mode}_" + _rand(_B62, 40)


def _gen_stripe_pub(mode: str = "live") -> str:
    """pk_{mode}_ + 40 alphanumeric chars."""
    return f"pk_{mode}_" + _rand(_B62, 40)


def _gen_jwt() -> str:
    """
    Synthetic JWT with a plausible structure.
    Header and payload are real base64url JSON; signature is random.
    """
    header  = base64.urlsafe_b64encode(b'{"alg":"HS256","typ":"JWT"}').rstrip(b"=").decode()
    payload_data = json.dumps({
        "sub":  _rand(_DIG, 10),
        "name": "SyntheticUser",
        "iat":  1_516_239_022 + RNG.randint(0, 10_000_000),
    }).encode()
    payload   = base64.urlsafe_b64encode(payload_data).rstrip(b"=").decode()
    signature = _rand(_B64U, 43)
    return f"{header}.{payload}.{signature}"


def _gen_openai_key() -> str:
    """sk-proj- + 20-char prefix + T3BlbkFJ + 24-char suffix (never real)."""
    prefix  = _rand(_B62, 21)
    suffix  = _rand(_B62, 25)
    return f"sk-proj-{prefix}T3BlbkFJ{suffix}"


def _gen_anthropic_key() -> str:
    """sk-ant-api03- + 93 alphanumeric chars."""
    return "sk-ant-api03-" + _rand(_B62 + "-_", 93)


def _gen_pem_header(kind: str = "RSA") -> str:
    return f"-----BEGIN {kind} PRIVATE KEY-----"


