"""
Evaluate the real-vs-placeholder classifier on the synthetic labeled corpus.

Workflow:
  1. Load data/corpus/corpus.jsonl (generated by data/generate_corpus.py).
  2. Construct a Finding from each sample (no detector involvement).
  3. Run secrettriage.classifier.classify() on the Finding.
  4. Compute precision / recall / F1 / confusion matrix globally and per secret type.
  5. Write results/eval.md with a full report.

Usage:
    python data/evaluate_corpus.py
"""
from __future__ import annotations

import json
import pathlib
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from typing import Any

ROOT = pathlib.Path(__file__).parent.parent
sys.path.insert(0, str(ROOT))

from secrettriage.detectors.models import Finding
from secrettriage.classifier.classifier import classify

CORPUS  = ROOT / "data" / "corpus" / "corpus.jsonl"
RESULTS = ROOT / "results" / "eval.md"


# ─────────────────────────────────────────────────────────────────────────────
# Helpers
# ─────────────────────────────────────────────────────────────────────────────

def load_corpus() -> list[dict[str, Any]]:
    samples = []
    with CORPUS.open(encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                samples.append(json.loads(line))
    return samples


def corpus_to_finding(s: dict[str, Any]) -> Finding:
    return Finding(
        file=s["file_path"],
        line=1,
        secret_type=s["secret_type"],
        matched_value=s["value"],
        context_before=s.get("context_before", []),
        context_after=s.get("context_after", []),
        detector_name="corpus",
        pattern_id=s.get("pattern_id", ""),
    )


@dataclass
class Counts:
    tp: int = 0   # truth=REAL,  pred=LIKELY_REAL
    fp: int = 0   # truth=PH,    pred=LIKELY_REAL
    tn: int = 0   # truth=PH,    pred=LIKELY_PLACEHOLDER
    fn: int = 0   # truth=REAL,  pred=LIKELY_PLACEHOLDER
    ur: int = 0   # truth=REAL,  pred=UNCERTAIN
    up: int = 0   # truth=PH,    pred=UNCERTAIN

    @property
    def precision(self) -> float:
        denom = self.tp + self.fp
        return self.tp / denom if denom else 0.0

    @property
    def recall(self) -> float:
        denom = self.tp + self.fn
        return self.tp / denom if denom else 0.0

    @property
    def f1(self) -> float:
        p, r = self.precision, self.recall
        return 2 * p * r / (p + r) if (p + r) else 0.0

    @property
    def accuracy(self) -> float:
        denom = self.tp + self.fp + self.tn + self.fn + self.ur + self.up
        return (self.tp + self.tn) / denom if denom else 0.0

    @property
    def total(self) -> int:
        return self.tp + self.fp + self.tn + self.fn + self.ur + self.up


def tally(truth_label: str, pred_label: str, counts: Counts) -> None:
    is_real = truth_label == "LIKELY_REAL"
    if pred_label == "LIKELY_REAL":
        if is_real:   counts.tp += 1
        else:         counts.fp += 1
    elif pred_label == "LIKELY_PLACEHOLDER":
        if is_real:   counts.fn += 1
        else:         counts.tn += 1
    else:  # UNCERTAIN
        if is_real:   counts.ur += 1
        else:         counts.up += 1


# ─────────────────────────────────────────────────────────────────────────────
# Report rendering
# ─────────────────────────────────────────────────────────────────────────────

def _pct(v: float) -> str:
    return f"{v * 100:.1f}%"


def render_report(
    global_counts: Counts,
    by_type: dict[str, Counts],
    total_samples: int,
    errors: list[str],
) -> str:
    lines = [
        "# Classifier Evaluation Report",
        "",
        "> **Generated by** `data/evaluate_corpus.py`  ",
        "> All corpus values are SYNTHETIC (see README §Ethics).  ",
        "",
        "## Global Metrics",
        "",
        f"| Metric | Value |",
        f"|---|---|",
        f"| Total samples         | {total_samples} |",
        f"| Precision (REAL)      | {_pct(global_counts.precision)} |",
        f"| Recall (REAL)         | {_pct(global_counts.recall)} |",
        f"| F1 (REAL)             | {_pct(global_counts.f1)} |",
        f"| Accuracy (hard calls) | {_pct(global_counts.accuracy)} |",
        "",
        "## Global Confusion Matrix",
        "",
        "Rows = **Ground truth**, Columns = **Predicted**",
        "",
        "| Truth \\ Predicted | LIKELY_REAL | LIKELY_PLACEHOLDER | UNCERTAIN |",
        "|---|---|---|---|",
        f"| LIKELY_REAL        | {global_counts.tp} (TP) | {global_counts.fn} (FN) | {global_counts.ur} |",
        f"| LIKELY_PLACEHOLDER | {global_counts.fp} (FP) | {global_counts.tn} (TN) | {global_counts.up} |",
        "",
        "## Per–Secret-Type Metrics",
        "",
        "| Secret Type | N | Precision | Recall | F1 | TP | FP | TN | FN | Uncertain |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]

    for stype, c in sorted(by_type.items()):
        lines.append(
            f"| {stype} | {c.total} "
            f"| {_pct(c.precision)} | {_pct(c.recall)} | {_pct(c.f1)} "
            f"| {c.tp} | {c.fp} | {c.tn} | {c.fn} | {c.ur + c.up} |"
        )

    lines += [
        "",
        "## Signal Coverage Notes",
        "",
        "- **Known-placeholder list** catches canonical AWS / GitHub documentation examples exactly.",
        "- **Shannon entropy** is the strongest continuous signal; real secrets cluster above 4.5 bpc.",
        "- **Context keywords** (`example`, `dummy`, `changeme`, etc.) add heavy penalties per hit.",
        "- **File-path heuristics** downweight findings in `tests/`, `docs/`, `examples/`, and `*.md`.",
        "- **Repetition / sequential checks** catch all-same-char and alphabet-run placeholders.",
        "- `UNCERTAIN` is returned when signals conflict — e.g., high-entropy value in a test directory.",
        "",
    ]

    if errors:
        lines += ["## Errors During Evaluation", ""]
        for e in errors[:20]:
            lines.append(f"- {e}")
        lines.append("")

    return "\n".join(lines)


# ─────────────────────────────────────────────────────────────────────────────
# Main
# ─────────────────────────────────────────────────────────────────────────────

def main() -> None:
    if not CORPUS.exists():
        print(f"ERROR: corpus not found at {CORPUS}", file=sys.stderr)
        print("Run:  python data/generate_corpus.py", file=sys.stderr)
        sys.exit(1)

    samples = load_corpus()
    print(f"Loaded {len(samples)} corpus samples.")

    global_counts = Counts()
    by_type: dict[str, Counts] = defaultdict(Counts)
    errors: list[str] = []
    misclassified: list[dict] = []

    for s in samples:
        try:
            finding = corpus_to_finding(s)
            classify(finding)
        except Exception as exc:
            errors.append(f"Sample {s['id']} ({s['secret_type']}): {exc}")
            continue

        truth = s["label"]
        pred  = finding.label

        tally(truth, pred, global_counts)
        tally(truth, pred, by_type[s["secret_type"]])

        if truth == "LIKELY_REAL" and pred == "LIKELY_PLACEHOLDER":
            misclassified.append({"id": s["id"], "type": s["secret_type"],
                                   "truth": truth, "pred": pred,
                                   "reasons": finding.label_reasons})
        elif truth == "LIKELY_PLACEHOLDER" and pred == "LIKELY_REAL":
            misclassified.append({"id": s["id"], "type": s["secret_type"],
                                   "truth": truth, "pred": pred,
                                   "reasons": finding.label_reasons})

    # Print to stdout
    print(f"\n=== Global Metrics ===")
    print(f"Precision : {_pct(global_counts.precision)}")
    print(f"Recall    : {_pct(global_counts.recall)}")
    print(f"F1        : {_pct(global_counts.f1)}")
    print(f"Accuracy  : {_pct(global_counts.accuracy)}")
    print(f"\nConfusion Matrix:")
    print(f"  TP={global_counts.tp}  FN={global_counts.fn}  UR={global_counts.ur}")
    print(f"  FP={global_counts.fp}  TN={global_counts.tn}  UP={global_counts.up}")

    if misclassified:
        print(f"\n--- {len(misclassified)} hard misclassification(s) ---")
        for m in misclassified:
            print(f"  id={m['id']} type={m['type']} truth={m['truth']} pred={m['pred']}")
            for r in m["reasons"][:3]:
                print(f"    • {r}")

    # Write eval.md
    RESULTS.parent.mkdir(parents=True, exist_ok=True)
    report = render_report(global_counts, by_type, len(samples), errors)
    RESULTS.write_text(report, encoding="utf-8")
    print(f"\n[OK] Evaluation report written to {RESULTS}")


if __name__ == "__main__":
    main()
